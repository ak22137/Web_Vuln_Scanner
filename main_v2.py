        def parse_vulnerability_entries(text):
            """Parse the text file into separate vulnerability entries"""
            entries = []
            current_entry = {}
            lines = text.split('\n')
            
            for line in lines:
                if line.startswith('Test:'):
                    if current_entry:
                        entries.append(current_entry)
                    current_entry = {'Test': line[5:].strip()}
                elif line.startswith('Vulnerability Definition:'):
                    current_entry['Definition'] = line[24:].strip()
                elif line.startswith('Vulnerability Remediation:'):
                    current_entry['Remediation'] = line[25:].strip()
            
            if current_entry:
                entries.append(current_entry)
            
            return entries
        
