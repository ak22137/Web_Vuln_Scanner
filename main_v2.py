        def process_vulnerability_entries(entries, tokenizer, model):
            """Process each vulnerability entry and calculate threat level"""
            results = []
            
            for entry in entries:
                # Combine entry information into a single text
                input_text = f"Test: {entry['Test']}\nDefinition: {entry['Definition']}\nRemediation: {entry['Remediation']}"
                
                # Generate threat score for this entry
                input_ids = tokenizer(input_text, return_tensors="pt").input_ids
                outputs = model.generate(input_ids)
                raw_output = tokenizer.decode(outputs[0])
                
                # Extract number from output
                number_match = re.search(r'(\d+\.?\d*)', raw_output)
                if number_match:
                    score = float(number_match.group(1))
                    
                    # Categorize individual threat level
                    if 0 <= score <= 4:
                        threat_level = f"Low-{score:.2f}"
                    elif 4.1 <= score <= 7:
                        threat_level = f"Medium-{score:.2f}"
                    elif 7.1 <= score <= 10:
                        threat_level = f"High-{score:.2f}"
                    else:
                        threat_level = "Invalid Score Range"
                        
                    results.append({
                        'name': entry['Test'],
                        'score': score,
                        'threat_level': threat_level
                    })
            
            return results
        
